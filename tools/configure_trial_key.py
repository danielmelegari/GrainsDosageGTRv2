"""Turn the public GitHub Actions variable into the C++ verification header."""
import base64
import os
import struct
import sys
from pathlib import Path

value = os.environ.get("GRAINS_TRIAL_PUBLIC_KEY", "")
if not value:
    sys.exit("Set repository variable GRAINS_TRIAL_PUBLIC_KEY to the .b64 public key generated by issue_trial_license.py keygen. See OFFLINE-TRIAL.md. Never upload the private PEM key.")
try:
    blob = base64.b64decode(value.strip(), validate=True)
    magic, bits, exponent, modulus, p1, p2 = struct.unpack("<6I", blob[:24])
    assert (magic, bits, modulus, p1, p2) == (0x31415352, 2048, 256, 0, 0)
    assert exponent == 3 and len(blob) == 24 + exponent + modulus
    assert blob[24:27] == b"\x01\x00\x01" and blob[27] & 0x80
except (ValueError, AssertionError, struct.error):
    sys.exit("Invalid RSA-2048 public verification key")
Path(sys.argv[1]).write_text("#pragma once\nnamespace grains::trial {\ninline constexpr unsigned char trialPublicKey[] = {" +
    ",".join(str(b) for b in blob) + "};\n}\n", encoding="utf-8")
